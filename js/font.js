for (const k in G) G[k] = G[k].replace(/ /g, '');

export const measure = (text, scale) => text.length * 6 * scale - scale + 2;

// (x, y): angolo in alto a sinistra, contorno compreso
export function drawText(g, text, x, y, scale, fill, edge = '#05081a', shadow = null) {
  const on = [];
  for (let i = 0; i < text.length; i++) {
    const glyph = G[text[i]] || G[text[i].toUpperCase()] || G[' '];
    const top = 7 - glyph.length / 5;                               // le lettere accentate salgono sopra la riga
    for (let p = 0; p < glyph.length; p++) if (glyph[p] === '#') on.push(i * 6 + (p % 5), top + ((p / 5) | 0));
  }
  const X = v => x + 1 + v * scale, Y = v => y + 1 + v * scale;
  if (shadow) { g.fillStyle = shadow; for (let k = 0; k < on.length; k += 2) g.fillRect(X(on[k]) - 1, Y(on[k + 1]) + 1, scale + 2, scale + 2); }
  if (edge) { g.fillStyle = edge; for (let k = 0; k < on.length; k += 2) g.fillRect(X(on[k]) - 1, Y(on[k + 1]) - 1, scale + 2, scale + 2); }
  g.fillStyle = fill;
  for (let k = 0; k < on.length; k += 2) g.fillRect(X(on[k]), Y(on[k + 1]), scale, scale);
}

const cache = new Map();
export function textSprite(text, scale, fill, edge = '#05081a', shadow = null) {
  const key = `${text}|${scale}|${fill}|${edge}|${shadow}`;
  if (cache.has(key)) return cache.get(key);
  const c = document.createElement('canvas');
  c.width = measure(text, scale);
  c.height = 7 * scale + 2 + (shadow ? 1 : 0);
  drawText(c.getContext('2d'), text, 0, 0, scale, fill, edge, shadow);
  cache.set(key, c);
  return c;
}
